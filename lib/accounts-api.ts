// HTTP handlers of "Konten verwalten" (R2, ADR 0023). Thin: session/CSRF/limit gate, body check (zod), lib/mail-accounts.ts.
// Scoped by the session's userId in every mode (the transitional modes act as the owner, user 1); a foreign id is 404.
// Responses never contain a password, ciphertext, nonce, tag or key; they show `secret_set` and `secret_set_at`.
import type { DatabaseSync } from "node:sqlite";
import { validateDatabasePath } from "./accounts.ts";
import { loadKeyring } from "./account-secrets.ts";
import { type AuthContext, createMutationLimiter, defaultAuthContext, defaultMutationLimiter, guardMutation, requireUser } from "./auth-runtime.ts";
import { PROJECT_ROOT } from "./constants.ts";
import { defaultConnector, testConnection, type TestConnector } from "./connection-test.ts";
import { openDatabase } from "./db.ts";
import {
  allowPrivateHosts, createAccountBody, createMailAccount, getAccountView, listAccountViews, loadConnection, recordTestResult,
  setAccountEnabled, updateAccountBody, updateMailAccount, type AccountError,
} from "./mail-accounts.ts";
import type { RateLimiter } from "./rate-limit.ts";

export interface AccountsApiDeps {
  auth: AuthContext;
  limiter: RateLimiter;
  /** Connection tests are slow and reach the outside world: a tighter budget per identity. */
  testLimiter: RateLimiter;
  openDb(): DatabaseSync;
  env: Record<string, string | undefined>;
  connector?: TestConnector;
  now?: () => Date;
}

const TEST_LIMIT = 10;
let defaultTest: RateLimiter | undefined;

export function defaultAccountsDeps(): AccountsApiDeps {
  return {
    auth: defaultAuthContext(),
    limiter: defaultMutationLimiter(),
    testLimiter: (defaultTest ??= createMutationLimiter(undefined, TEST_LIMIT)),
    openDb: () => openDatabase(validateDatabasePath(process.env, PROJECT_ROOT)),
    env: process.env,
  };
}

const json = (body: unknown, status = 200) => Response.json(body, { status, headers: { "cache-control": "no-store" } });
const BODY_MAX_CHARS = 8192;

const ERROR_STATUS = (code: AccountError): number =>
  code === "not_found" ? 404 : code === "no_encryption_key" ? 503 : code === "not_managed" ? 409 : 400;

async function readBody(request: Request): Promise<unknown | undefined> {
  try {
    const text = await request.text();
    if (text.length > BODY_MAX_CHARS) return undefined;
    return text.trim() === "" ? {} : JSON.parse(text);
  } catch {
    return undefined;
  }
}

function withDb(deps: AccountsApiDeps, fn: (db: DatabaseSync) => Response): Response {
  let db: DatabaseSync | undefined;
  try {
    db = deps.openDb();
    return fn(db);
  } catch {
    return json({ error: "unavailable" }, 500);
  } finally {
    db?.close();
  }
}

/** GET /api/accounts: the user's accounts (no secrets) and whether secrets can be stored at all. */
export function handleAccountsList(request: Request, deps: AccountsApiDeps): Response {
  const who = requireUser(request, deps.auth);
  if (!who.ok) return who.response;
  return withDb(deps, (db) => json({
    accounts: listAccountViews(db, who.userId),
    encryption: { ready: loadKeyring(deps.env).ok },
    synthetic: deps.auth.synthetic,
  }));
}

/** POST /api/accounts: creates an account (id generated by the server). */
export async function handleAccountCreate(request: Request, deps: AccountsApiDeps): Promise<Response> {
  const gate = guardMutation(request, deps.auth, deps.limiter);
  if (!gate.ok) return gate.response;
  const body = await readBody(request);
  const parsed = createAccountBody.safeParse(body);
  if (!parsed.success) return json({ error: "invalid_body", fields: [...new Set(parsed.error.issues.map((i) => i.path.join(".")))].slice(0, 10) }, 400);
  return withDb(deps, (db) => {
    const r = createMailAccount(db, gate.userId, loadKeyring(deps.env), parsed.data, { ...(deps.now ? { now: deps.now() } : {}), allowPrivate: allowPrivateHosts(deps.env) });
    if (!r.ok) return json({ error: r.code }, ERROR_STATUS(r.code));
    return json({ ok: true, account: getAccountView(db, gate.userId, r.id) }, 201);
  });
}

/** POST /api/accounts/:id: updates; an absent or empty `password` keeps the stored secret. */
export async function handleAccountUpdate(request: Request, id: string, deps: AccountsApiDeps): Promise<Response> {
  const gate = guardMutation(request, deps.auth, deps.limiter);
  if (!gate.ok) return gate.response;
  const body = await readBody(request);
  const parsed = updateAccountBody.safeParse(body);
  if (!parsed.success) return json({ error: "invalid_body", fields: [...new Set(parsed.error.issues.map((i) => i.path.join(".")))].slice(0, 10) }, 400);
  return withDb(deps, (db) => {
    const r = updateMailAccount(db, gate.userId, id, loadKeyring(deps.env), parsed.data, { ...(deps.now ? { now: deps.now() } : {}), allowPrivate: allowPrivateHosts(deps.env) });
    if (!r.ok) return json({ error: r.code }, ERROR_STATUS(r.code));
    return json({ ok: true, account: getAccountView(db, gate.userId, id) });
  });
}

/** POST /api/accounts/:id/disable and /enable. The supervisor in the server process picks the change up within seconds. */
export function handleAccountEnabled(request: Request, id: string, enabled: boolean, deps: AccountsApiDeps): Response {
  const gate = guardMutation(request, deps.auth, deps.limiter);
  if (!gate.ok) return gate.response;
  return withDb(deps, (db) => {
    if (setAccountEnabled(db, gate.userId, id, enabled, deps.now?.()) === "not_found") return json({ error: "not_found" }, 404);
    return json({ ok: true, account: getAccountView(db, gate.userId, id) });
  });
}

/** POST /api/accounts/:id/test: read-only connection test (LIST only). Synthetic mode never connects. */
export async function handleAccountTest(request: Request, id: string, deps: AccountsApiDeps): Promise<Response> {
  const gate = guardMutation(request, deps.auth, deps.limiter);
  if (!gate.ok) return gate.response;
  const owned = withDb(deps, (db) => json({ found: getAccountView(db, gate.userId, id) !== null }));
  if (owned.status !== 200) return owned;
  if (!((await owned.json()) as { found: boolean }).found) return json({ error: "not_found" }, 404);
  if (deps.auth.synthetic) return json({ ok: false, code: "synthetic_no_network" });
  const lim = deps.testLimiter.check(gate.login);
  if (!lim.allowed) {
    return new Response(JSON.stringify({ error: "rate_limited" }), {
      status: 429,
      headers: { "content-type": "application/json", "retry-after": String(Math.ceil(lim.retryAfterMs / 1000)), "cache-control": "no-store" },
    });
  }
  const keys = loadKeyring(deps.env);
  if (!keys.ok) return json({ error: "no_encryption_key" }, 503);
  let target: ReturnType<typeof loadConnection>;
  try {
    const db = deps.openDb();
    try {
      target = loadConnection(db, gate.userId, id, keys.keyring);
    } finally {
      db.close();
    }
  } catch {
    return json({ error: "unavailable" }, 500);
  }
  if (target === null) return json({ error: "not_managed" }, 409);
  if (target === "unreadable") return json({ error: "secret_unreadable" }, 409);
  const code = await testConnection(target, deps.connector ?? defaultConnector);
  return withDb(deps, (db) => {
    recordTestResult(db, gate.userId, id, code, deps.now?.());
    return json({ ok: code === "ok", code });
  });
}
